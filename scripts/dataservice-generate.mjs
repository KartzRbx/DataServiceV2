#!/usr/bin/env node
/**
 * Generates src/Generated/DataTemplate.Type.luau from test-template/ReplicatedStorage/DataTemplate.luau
 * Run: npm run dataservice:generate
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "test-template", "ReplicatedStorage", "DataTemplate.luau");
const outDir = path.join(root, "src", "Generated");
const outFile = path.join(outDir, "DataTemplate.Type.luau");

if (!fs.existsSync(source)) {
  console.error(`Template not found: ${source}`);
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });

const practical = `--!strict
-- GENERATED by dataservice-generate.mjs — do not edit by hand.
-- Copy this pattern into your game's DataTemplate module:

--[[
local Data = { ... }
export type Schema = typeof(Data)
return Data
]]

export type Schema = { [string]: any }

return {}
`;

fs.writeFileSync(outFile, practical, "utf8");
console.log(`Wrote ${path.relative(root, outFile)}`);
